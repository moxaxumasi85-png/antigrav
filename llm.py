def fix_female_endings(text: str) -> str:
    if not text:
        return text
    text = re.sub(r'([а-яА-ЯёЁ]+л)А\b', r'\1а', text)
    text = re.sub(r'([а-яА-ЯёЁ]+д)А\b', r'\1а', text)
    return text

